#!/usr/bin/env python3
"""Рендеры из media/renders/ → media/opt/: AVIF и WebP в ширинах 640/1280/1920
(не больше ширины исходника; у рендеров из WhatsApp — 640 и 1080) + JPG-запасной.
То же, что tools/images.mjs, но на Pillow — без node.

  .venv/bin/python tools/images.py syr-dusk-front syr-courtyard …
"""
import json
import os
import sys

from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC, OUT = os.path.join(ROOT, 'media/renders'), os.path.join(ROOT, 'media/opt')
ORIGIN = ('Origin: resized by tools/images.py from media/renders/%s.jpg (a project render supplied by the client); '
          'not generated by Impeccable.')


def prov(fn, base):
    with open(fn + '.json', 'w', encoding='utf-8') as fh:
        json.dump({'prompt': ORIGIN % base, 'createdAt': '2026-10-27T00:00:00.000Z'}, fh, ensure_ascii=False, indent=2)
        fh.write('\n')


def widths(w):
    out = [x for x in (640, 1280, 1920) if x < w]
    return out + [w] if not out or out[-1] != w and w < 1920 else out


for base in sys.argv[1:]:
    im = Image.open(os.path.join(SRC, base + '.jpg')).convert('RGB')
    ws = sorted(set(min(x, im.width) for x in widths(im.width)))
    for w in ws:
        r = im if w == im.width else im.resize((w, round(im.height * w / im.width)), Image.LANCZOS)
        f = os.path.join(OUT, '%s-%d' % (base, w))
        r.save(f + '.avif', 'AVIF', quality=60 if w < 1900 else 56)
        prov(f + '.avif', base)
        r.save(f + '.webp', 'WEBP', quality=76, method=6)
        prov(f + '.webp', base)
    mid = ws[1] if len(ws) > 1 else ws[0]
    r = im if mid == im.width else im.resize((mid, round(im.height * mid / im.width)), Image.LANCZOS)
    r.save(os.path.join(OUT, '%s-%d.jpg' % (base, mid)), 'JPEG', quality=80, optimize=True, progressive=True)
    print('✓', base, im.size, ws)
